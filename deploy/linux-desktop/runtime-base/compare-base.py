#!/usr/bin/env python3
"""Compare a rebuilt dependency base with a qualified runtime image.

Both filesystems are exported from unstarted, network-less containers with the
same method as compact-runtime.py. Every path must match in type, bytes, mode,
owner, link target, hardlink group and xattrs, except the categories in RULES.
Nothing is started, pushed, tagged or deleted besides the temporary containers.
"""

import argparse
from fnmatch import fnmatchcase
import importlib.util
import io
import json
import os
from pathlib import Path
import subprocess
import tarfile

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("compact_runtime", HERE.parent / "compact-runtime.py")
compact_runtime = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(compact_runtime)

# (category, patterns). Paths are relative to /, as exported by Docker.
RULES = [
    # Cindy-owned programs and desktop integration ship with the application
    # layer, so the third-party base must not contain them.
    ("release-layer", [
        "opt/cindy", "opt/cindy/*",
        "usr/local/bin/cindy-*", "usr/local/bin/claude", "usr/local/bin/codex",
        "usr/local/lib/cindy", "usr/local/lib/cindy/*",
        "usr/local/share/cindy", "usr/local/share/cindy/*",
        "usr/share/applications/com.cindy.*.desktop",
        "usr/share/themes/Cindy-Cloud", "usr/share/themes/Cindy-Cloud/*",
        "run/cindy-profile-check", "run/cindy-profile-check/*",
    ]),
    # Caches left by earlier builds: corepack in root's unreachable home, a
    # Rosetta translation cache, a GitHub CLI device ID and a Node compile cache.
    ("build-leftover", [
        "root/.cache", "root/.cache/*",
        "home/cindy/.cache", "home/cindy/.cache/*",
        "home/cindy/.local", "home/cindy/.local/*",
        "tmp/*",
    ]),
    # Rewritten on purpose: the snapshot replaces a regional mirror.
    ("changed-by-design", ["etc/apt/sources.list.d/debian.sources"]),
    # Package bookkeeping written in installation order. The sorted records must
    # be identical; dpkg's own status database is still compared byte for byte.
    ("order-insensitive", [
        "var/lib/apt/extended_states", "var/lib/dpkg/triggers/File",
        "usr/share/applications/bamf-2.index",
    ]),
    # dpkg's backup of the status before its last transaction.
    ("transient", ["var/lib/dpkg/status-old"]),
    # Build logs and caches regenerated by package scripts. Type, owner and mode
    # must still match; their bytes record build time and are not payload.
    ("regenerated", ["var/log/*", "var/cache/*"]),
]
STANZAS = {"var/lib/apt/extended_states"}
CONTENT_FIELDS = ("size", "sha256", "hardlinks", "target")


def category(path):
    for name, patterns in RULES:
        if any(fnmatchcase(path, pattern) for pattern in patterns):
            return name
    return None


def metadata(row):
    return {k: v for k, v in row.items() if k not in CONTENT_FIELDS}


def records(path, data):
    text = data.decode("utf-8")
    if path in STANZAS:
        return sorted(block.strip() for block in text.split("\n\n") if block.strip())
    return sorted(text.splitlines())


def order_paths(reference, candidate):
    return [path for path in sorted(reference.keys() | candidate.keys())
            if category(path) == "order-insensitive" and reference.get(path) != candidate.get(path)
            and reference.get(path) and candidate.get(path)]


def classify(reference, candidate, contents=None):
    """Return per-category paths and the unexpected differences.

    contents maps each order_paths() entry to (reference bytes, candidate bytes).
    """
    contents = contents or {}
    result = {name: [] for name, _ in RULES}
    result["unexpected"] = []
    for path in sorted(reference.keys() | candidate.keys()):
        ref, new = reference.get(path), candidate.get(path)
        kind = category(path)
        # These paths must be absent even when copied byte-for-byte from the
        # reference. Equality alone cannot qualify an application-free base.
        if kind in ("release-layer", "build-leftover") and new is not None:
            result["unexpected"].append(path)
            continue
        if ref == new:
            continue
        both = ref is not None and new is not None and metadata(ref) == metadata(new)
        if kind in ("release-layer", "build-leftover"):
            # Allowed only as absences from the rebuilt base.
            ok = new is None
        elif kind in ("changed-by-design", "transient"):
            ok = both
        elif kind == "order-insensitive":
            ok = both and path in contents and \
                records(path, contents[path][0]) == records(path, contents[path][1])
        elif kind == "regenerated":
            ok = ref is None or new is None or metadata(ref) == metadata(new)
        else:
            ok = False
        result[kind if ok else "unexpected"].append(path)
    return result


def read_files(image, paths):
    """Read regular files from an unstarted container."""
    container = compact_runtime.docker("create", "--network", "none", "--entrypoint", "/bin/true", image)
    try:
        result = {}
        for path in paths:
            archive = subprocess.run(["docker", "cp", f"{container}:/{path}", "-"],
                                     check=True, stdout=subprocess.PIPE).stdout
            with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
                member = tar.next()
                if member is None or not member.isfile():
                    raise ValueError(f"not a regular file: {path}")
                result[path] = tar.extractfile(member).read()
        return result
    finally:
        subprocess.run(["docker", "rm", container], check=True, stdout=subprocess.DEVNULL)


def check_config(info):
    config = info["Config"]
    problems = []
    if (info["Os"], info["Architecture"]) != ("linux", "amd64"):
        problems.append("platform")
    if len(info["RootFS"]["Layers"]) != 1:
        problems.append("layers")
    if config.get("Entrypoint") or config.get("Cmd"):
        problems.append("start-command")
    if config.get("User") not in (None, ""):
        problems.append("user")
    env = dict(e.split("=", 1) for e in config.get("Env") or [])
    if env.get("LANG") != "zh_CN.UTF-8" or env.get("NODE_VERSION") != "24.19.0":
        problems.append("env")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", required=True, help="qualified runtime image ID or digest")
    parser.add_argument("--candidate", required=True, help="rebuilt base image ID or digest")
    parser.add_argument("--output", required=True, type=Path, help="new evidence directory")
    args = parser.parse_args()
    for image in (args.reference, args.candidate):
        compact_runtime.source_reference(image)  # rejects mutable tags
    os.umask(0o077)
    args.output.mkdir(mode=0o700, parents=True, exist_ok=False)
    reference_info = compact_runtime.inspect(args.reference)
    candidate_info = compact_runtime.inspect(args.candidate)
    reference = compact_runtime.filesystem(reference_info["Id"])
    candidate = compact_runtime.filesystem(candidate_info["Id"])
    for name, value in [("reference", reference), ("candidate", candidate)]:
        compact_runtime.save(args.output / f"{name}-filesystem.json", value)
    paths = order_paths(reference, candidate)
    ref_files = read_files(reference_info["Id"], paths)
    new_files = read_files(candidate_info["Id"], paths)
    classes = classify(reference, candidate, {p: (ref_files[p], new_files[p]) for p in paths})
    config_problems = check_config(candidate_info)
    result = {
        "referenceId": reference_info["Id"], "candidateId": candidate_info["Id"],
        "referenceEntries": len(reference), "candidateEntries": len(candidate),
        "candidateLayers": len(candidate_info["RootFS"]["Layers"]),
        "candidateBytes": candidate_info["Size"],
        "configProblems": config_problems,
        **{name: paths for name, paths in classes.items()},
        "published": False, "runtimeExecuted": False,
    }
    result["passed"] = not classes["unexpected"] and not config_problems
    compact_runtime.save(args.output / "verification.json", result)
    summary = {k: (len(v) if isinstance(v, list) else v) for k, v in result.items()}
    print(json.dumps(summary, indent=2))
    if not result["passed"]:
        raise SystemExit("Rebuilt base differs from the qualified image; see verification.json")


if __name__ == "__main__":
    main()
